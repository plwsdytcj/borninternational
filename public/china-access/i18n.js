  const textOriginals = new WeakMap();
  const attributeOriginals = new WeakMap();
  const languageButtons = [...document.querySelectorAll('[data-language-choice]')];

  function translateTextNode(node, language) {
    if (!textOriginals.has(node)) textOriginals.set(node, node.nodeValue);
    const original = textOriginals.get(node);
    const key = original.trim();
    if (!key) return;
    const leading = original.match(/^\s*/)?.[0] || '';
    const trailing = original.match(/\s*$/)?.[0] || '';
    node.nodeValue = language === 'ru' && ru[key] ? `${leading}${ru[key]}${trailing}` : original;
  }

  function translateAttributes(element, language) {
    const names = ['alt', 'aria-label', 'placeholder', 'title'];
    if (!attributeOriginals.has(element)) attributeOriginals.set(element, {});
    const originals = attributeOriginals.get(element);
    names.forEach(name => {
      if (!element.hasAttribute(name)) return;
      if (!(name in originals)) originals[name] = element.getAttribute(name);
      const original = originals[name];
      element.setAttribute(name, language === 'ru' && ru[original] ? ru[original] : original);
    });
  }

  function applyLanguage(language) {
    const resolved = language === 'en' ? 'en' : 'ru';
    const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT);
    let node;
    while ((node = walker.nextNode())) translateTextNode(node, resolved);
    document.querySelectorAll('[alt],[aria-label],[placeholder],[title]').forEach(el => translateAttributes(el, resolved));
    document.documentElement.lang = resolved;
    document.documentElement.dataset.language = resolved;
    localStorage.setItem('boln-language', resolved);
    languageButtons.forEach(button => button.setAttribute('aria-pressed', String(button.dataset.languageChoice === resolved)));
    document.title = resolved === 'ru'
      ? 'China Access | BORN International'
      : 'China Access | BORN International';
    const description = document.querySelector('meta[name="description"]');
    if (description) description.content = resolved === 'ru'
      ? 'China Access от BORN International помогает компаниям находить и проверять поставщиков в Китае и выстраивать долгосрочное сотрудничество.'
      : 'BORN International China Access helps companies discover and verify suppliers in China and build long-term partnerships.';
    window.dispatchEvent(new CustomEvent('boln:languagechange', { detail: { language: resolved } }));
  }

  languageButtons.forEach(button => button.addEventListener('click', () => applyLanguage(button.dataset.languageChoice)));
  applyLanguage(document.documentElement.dataset.language || localStorage.getItem('boln-language') || 'ru');

  window.BOLNI18N = {
    applyLanguage,
    getLanguage: () => document.documentElement.lang,
    translate: key => document.documentElement.lang === 'ru' ? (ru[key] || key) : key
  };
